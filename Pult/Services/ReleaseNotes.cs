    public static string Current()
    {
        try
        {
            return Assembly.GetExecutingAssembly()
                .GetCustomAttribute<AssemblyInformationalVersionAttribute>()
                ?.InformationalVersion ?? "";
        }
        catch { return ""; }
    }

    public static bool IsCurrent(string version)
    {
        try
        {
            string cur = Current();
            return cur.Length > 0 && cur.StartsWith(version, StringComparison.Ordinal);
        }
        catch { return false; }
    }

    public static string Format()
    {
        try
        {
            string cur = Current();
            var sb = new System.Text.StringBuilder();
            sb.AppendLine("Что менялось по версиям (новейшее сверху).");
            foreach (var n in All)
            {
                sb.AppendLine();
                sb.Append("== ").Append(n.Version);
                if (IsCurrent(n.Version))
                    sb.Append(" (текущая)");
                sb.AppendLine();
                foreach (string item in n.Items)
                    sb.AppendLine("• " + item);
            }
            return sb.ToString().Trim();
        }
        catch (Exception ex) { return "Ошибка: " + ex.Message; }
    }
